    "\n",
    "\n",
    "def digit_to_letter(digit):\n",
    "    \"\"\"\"1\" -> \"A\", \"2\" -> \"B\", ... \"INVALID\" passes through unchanged.\"\"\"\n",
    "    if digit.isdigit() and 1 <= int(digit) <= 26:\n",
